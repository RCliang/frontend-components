const termIds = new Set<string>(Object.values(terms).map((term) => term.id))

export function isTermId(id: string): id is TermId {
  return termIds.has(id)
}

export function findTerm(id: string): Term | undefined {
  if (!isTermId(id)) return undefined
  return terms[id]
}
